// app.c の起動診断ブレッドクラム
extern volatile uint32_t g_diag_step;

// フォールト発生時に原因レジスタを吐き出す。
// 正確な faulting PC はデバッガで確認する前提で、ここでは
// 「どの種類のフォールトか」「Setupのどこで起きたか」までを出す。
static void DiagReportFault(const char *name)
{
  uint32_t cfsr = SCB->CFSR;

  printf("\r\n[FAULT] %s at diag_step=%lu\r\n", name,
         (unsigned long)g_diag_step);
  printf("  HFSR =0x%08lX  CFSR=0x%08lX\r\n", (unsigned long)SCB->HFSR,
         (unsigned long)cfsr);
  printf("  MMFSR=0x%02lX BFSR=0x%02lX UFSR=0x%04lX\r\n",
         (unsigned long)(cfsr & 0xFFU), (unsigned long)((cfsr >> 8) & 0xFFU),
         (unsigned long)((cfsr >> 16) & 0xFFFFU));
  if (cfsr & SCB_CFSR_MMARVALID_Msk) {
    printf("  MMFAR=0x%08lX\r\n", (unsigned long)SCB->MMFAR);
  }
  if (cfsr & SCB_CFSR_BFARVALID_Msk) {
    printf("  BFAR =0x%08lX\r\n", (unsigned long)SCB->BFAR);
  }
  if (cfsr & SCB_CFSR_DIVBYZERO_Msk)  printf("  -> divide by zero\r\n");
  if (cfsr & SCB_CFSR_UNALIGNED_Msk)  printf("  -> unaligned access\r\n");
  if (cfsr & SCB_CFSR_UNDEFINSTR_Msk) printf("  -> undefined instruction\r\n");
  if (cfsr & SCB_CFSR_INVSTATE_Msk)   printf("  -> invalid state (bad function pointer?)\r\n");
  if (cfsr & SCB_CFSR_PRECISERR_Msk)  printf("  -> precise bus error (BFAR is the address)\r\n");
  if (cfsr & SCB_CFSR_IMPRECISERR_Msk)printf("  -> imprecise bus error\r\n");
  printf("  halt.\r\n");
}
